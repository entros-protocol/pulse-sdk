/**
 * Standardize the 170-dimensional speaker feature block against frozen
 * population reference statistics and clamp each dimension to [-6, 6].
 */
export function standardizeAudioV2(audioFeatures: readonly number[]): number[] {
  return audioFeatures.map((value, index) => {
    const clean = Number.isFinite(value) ? value : 0;
    const mean = AUDIO_REF_MEAN_V2[index] ?? 0;
    const std = AUDIO_REF_STD_V2[index] ?? 0;
    if (std < 1e-8) {
      return 0;
    }
    const z = (clean - mean) / std;
    return Math.max(-AUDIO_REF_CLAMP_V2, Math.min(AUDIO_REF_CLAMP_V2, z));
  });
}

/**
 * Apply sign-preserving log1p compression (`sign(x) * ln(1 + |x|)`) to the
 * 81-dimensional motion feature block before within-block z-score normalization.
 */
export function signedLog1pMotion(motionFeatures: readonly number[]): number[] {
  return motionFeatures.map((value) => {
    if (!Number.isFinite(value) || value === 0) {
      return 0;
    }
    return Math.sign(value) * Math.log1p(Math.abs(value));
  });
}

/**
 * Normalize and concatenate modality feature blocks for the requested projection
 * version.
 *
 * - Projections 0 and 1: within-block `normalizeGroup` on audio, motion, and touch.
 * - Projection 2+: population reference standardization on audio (`0..170`),
 *   signed `log1p` followed by `normalizeGroup` on motion (`170..251`), and
 *   within-block `normalizeGroup` on normalized-touch (`251..308`).
 */
export function fuseFeaturesForProjection(
  audioFeatures: readonly number[],
  motionFeatures: readonly number[],
  touchFeatures: readonly number[],
  projectionVersion = 0,
): number[] {
  if (projectionVersion < 2) {
    return fuseFeatures(
      [...audioFeatures],
      [...motionFeatures],
      [...touchFeatures],
    );
  }
  return [
    ...standardizeAudioV2(audioFeatures),
    ...normalizeGroup(signedLog1pMotion(motionFeatures)),
    ...normalizeGroup([...touchFeatures]),
  ];
}

export function normalizeFeaturesForProjection(
  rawFeatures: readonly number[],
  projectionVersion = 0,
): number[] {
  const audioEnd = SPEAKER_FEATURE_COUNT;
  const motionEnd = audioEnd + MOTION_FEATURE_COUNT;
  const touchEnd = motionEnd + TOUCH_FEATURE_COUNT;
  return fuseFeaturesForProjection(
    rawFeatures.slice(0, audioEnd),
    rawFeatures.slice(audioEnd, motionEnd),
    rawFeatures.slice(motionEnd, touchEnd),
    projectionVersion,
  );
}
